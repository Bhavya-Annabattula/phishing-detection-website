    report_lines.append("   -> Brand Token: 1 | Brand in RegDom: 0 | Brand in Subdomain: 1 | Brand Mismatch: 1")
    report_lines.append("   -> Path Segment Count: 1 | Excessive Subdomains: 0 | Hyphen Count: 2")
    report_lines.append("")
    report_lines.append("4. http://192.168.1.1/login.php")
    report_lines.append("   -> Hostname: 192.168.1.1 | Registered Domain: 192.168.1.1 | Subdomain: (empty)")
    report_lines.append("   -> Hostname Has IP: 1 | IP Address Host: 1 | Digits: 8 | Dots: 4")
    report_lines.append("```")
    report_lines.append("")
    report_lines.append("---")
    report_lines.append("")
    report_lines.append("## 6. EXTRACTION PERFORMANCE BENCHMARK")
